void SdData(uchar Command)
{
   uchar j;
   transdata=Command;
   A0	=  1;
   CS	=  0;
   for(j=0;j<8;j++)
   	{
	SDA=transbit;
	SCL=0;
	SCL=1;
	transdata=transdata<<1;
	}
   CS	=  1;
}
