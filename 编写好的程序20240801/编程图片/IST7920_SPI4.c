// ====================================//
// 按键处理函数(带定时功能总体定时约1ms*Xms)
// 输入参数:Xms
// 输出参数:暂停键按下标志
// 功能说明: 
// 1, 在定时过程中首先判断是否有暂停键按下,如有则定时失效,此时同时判断对比度上下调节键及暂停键,
//    如果对比度调节键有按下则进行对比度调整,如果暂停键有按下则记录下暂停键有按下的状态并返回一个"1"参数并退出程序.
// 2, 在定时过程中暂停键一直没有动作,则直接返回"0"参数并退出程序.
// ====================================//
unsigned char Change(unsigned int Xms)
{
	unsigned int i;
	unsigned char j,h;
	j=h=0;
	for(i=0;i<Xms;i++)
	{//需定时的ms数
		for(j=0;j<150;j++)
		{//定时的基数约1ms
			if( SW==0 )
			{//如果暂停键按下有效
				delayms(10);	//消抖动
				if ( SW==0 )
				{//暂停键按下有效
					while( SW==0 );	//等待暂停键弹起
					delayms(10);	//消抖动
					while(1)
					{
						if( SW==0 )
						{//暂停键再次按下
							delayms(10);	//消抖动
							if ( SW==0 )
							{//暂停键按下有效
								while( SW==0 );	//等待暂停键弹起
								delayms(10);	//消抖动
								h = 1;	//把暂停键标志置1
								goto Eixt;	//跳到退出程序标号
							}
						}
						else if( UP==0 )
						{//对比度+键按下
							delayms(5);	//消抖动
							if ( UP==0 )
							{//对比度+键按下有效
								while( UP==0 )	//等待此键弹起
								{
									if( DN==0 )
									{
										delayms(5);	//消抖动
										if ( DN==0 )
										{//对比度-键按下有效
											while( (DN==1)&&(UP==1) );	//等待此键弹起
											delayms(5);	//消抖动
											h = 1;	//把暂停键标志置1
											goto Eixt;	//跳到退出程序标号
										}
									}
								}
								delayms(5);	//消抖动
								ADJUST++;	//对比度寄存器加一档
								//======adjust contrast=====对比度设定
								SetContrast();	
								//==========================
							}				
						}
						else if( (DN==0)&&(UP==1) )
						{//对比度-键按下
							delayms(10);	//消抖动
							if ( DN==0 )
							{//对比度-键按下有效
								while( DN==0 );	//等待此键弹起
								delayms(5);	//消抖动
								ADJUST--;	//对比度寄存器减一档
								//======adjust contrast=====对比度设定
								SetContrast();	
								//==========================
							}				
						}
					}
				}
			}
		}
	}
	Eixt: delayms(1);	//退出程序标号
	return (h);	//返回参数
}

