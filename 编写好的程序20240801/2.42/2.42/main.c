void Display_Chess(unsigned char value)
{
    unsigned char i,j,k;
    for(i=0;i<0x08;i++)
	{
		Set_Page_Address(i);

        Set_Column_Address(0x00);

		for(j=0;j<0x10;j++)
		{
		    for(k=0;k<0x04;k++)
		        Write_Data(value);
		    for(k=0;k<0x04;k++)
		        Write_Data(~value);
		}
	}
    return;
}


