void Delay(unsigned int time)
{
	unsigned int i,j;
	for(i=0;i<time;i++)
	for(j=0;j<20000;j++)
	{;}
}

void Ins_trans(unsigned char command)
{
	unsigned char counter;
	_CS=0;
	DC=0;
	for(counter=0;counter<8;counter++)
	{
		SCLK=0;
		SDA=(command&0x80)>>7;
		command=command<<1;
		_nop_();
		SCLK=1;
		//  _nop_();
		_nop_();
		SCLK=0;
	}
	DC=1;
	_CS=1;
}

void Data_trans(unsigned char command)
{
	unsigned char counter;
	_CS=0;
	DC=1;
	for(counter=0;counter<8;counter++)
	{
		SCLK=0;
		SDA=(command&0x80)>>7;
		command=command<<1;
		_nop_();
		SCLK=1;
		// _nop_();
		_nop_();
		SCLK=0;
	}
	DC=1;
	_CS=1;
}

void Column_set(unsigned char column)
{
Ins_trans(0x10|(column>>4));
Ins_trans(0x00|(column&0x0f));
}

void Page_set(unsigned char page)
{
Ins_trans(0xb0+page);
}

void Screen_clearfill(unsigned char dat)
{
unsigned char page,column;
for(page=0;page<8;page++)             //page loop
	{ 
		Page_set(page);
		Column_set(0);	  
		for(column=0;column<128;column++)	//column loop
		{
		Data_trans(dat);
		}
	}
 }

void Initial()
{
Ins_trans(0xFD);//Set Command Lock
Ins_trans(0x12);//Unlock(0x12)

Ins_trans(0xAE);//Turn off oled panel(0xae)

Ins_trans(0x20);//Set Memory Addressing Mode
Ins_trans(0x02);//10b, Page Addressing Mode (0x02,RESET)

Ins_trans(0x40);//Set start line address(0x40)

Ins_trans(0x81);//(Set contrast control register)
Ins_trans(0xFF);//0xFF is Max.(0x7F)

Ins_trans(0xA1);//set segment re-map 127 to 0   (0xA0):0 to seg127
Ins_trans(0xC8);//set com(N-1)to com0  (0xC0):com0 to com(N-1)

Ins_trans(0xA4);//Set Entire Display On/(Off)
Ins_trans(0xA6);//Set (normal) display

Ins_trans(0xA8);//Set multiples ratio(1to64)
Ins_trans(0x3F);//1/64 duty

Ins_trans(0xD3);//Set display offset
Ins_trans(0x00);//Not offset(0x00)

Ins_trans(0xD5);//Set display clock divide ratio/oscillator frequency
Ins_trans(0x80);//Set divide ratio(0x70)

Ins_trans(0xD9);//Set pre-charge period
Ins_trans(0xF1);//(0X22)

Ins_trans(0xDA);//(Set com pins hardware configuration)
Ins_trans(0x12);//(0X12)

Ins_trans(0xDB);//Set vcomh
Ins_trans(0x40);//(0x34,0.78*Vcc)

Ins_trans(0xAF);//Turn on oled panel
}

void Picture_display(unsigned char *ptr_pic)
{
	unsigned char page,column;
	for(page=0;page<8;page++)        //page loop
	{
		Page_set(page);
		Column_set(0);
		for(column=0;column<128;column++)	//column loop
		{
		Data_trans(*ptr_pic++);
		}
	}
	Delay(15);
}

void disA5()
{
	unsigned char i,j;
	for(j=0;j<8;j++)
	{
		Page_set(j);
		Column_set(0);
		for(i=0;i<64;i++)
		{
		Data_trans(0xAA);
		Data_trans(0x55);
		}
	}
}

void main()
{ 
	RES=0;
	Delay(3);
	RES=1;
	Initial();
	while(1)
	{
	Screen_clearfill(0xff);//全显
	Delay(5);

	disA5();
	Delay(5);
	Picture_display(picture_tab);
	}
}


