void exdelay1(unsigned int ms)   // 传入延时时间，单位：毫秒
{
    unsigned int x, y, z;
    while(ms--)   // 每次循环延时 1ms
    {
        for(x = 0; x < 1; x++)
            for(y = 0; y < 64; y++)
                for(z = 0; z < 51; z++);
    }
}

