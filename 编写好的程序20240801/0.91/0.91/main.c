void clr_display3(void)
{
	Uchar i,j;
	for(j=0;j<4;j++)
	{
		Write_Command3(0x22);//--set page1
		Write_Command3(j);//--set start page
		Write_Command3(0x03);//--set end page

 		for(i=0;i<128;i++)		  				//显示单色数据到LCD
		{
			Write_Data3(0x00);
		}
	}
}
			
