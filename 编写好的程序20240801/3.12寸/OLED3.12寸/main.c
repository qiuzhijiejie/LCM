void send_2bit(unsigned char two_bit_data)
{
        if(two_bit_data==0x00)
                Data_trans(0x00);
        else if(two_bit_data==0x40)
                Data_trans(0x0f);
        else if(two_bit_data==0x80)
                Data_trans(0xf0);
        else
                Data_trans(0xff);
}

void Fill_Block(unsigned char Data, unsigned char a, unsigned char b, unsigned char c, unsigned char d)//填充区块
{
unsigned char i,j;
	Ins_trans(0x15); //set列地址
	Data_trans(0x1C+a);//列地址开始
	Data_trans(0x1C+b);//列地址结束
	Ins_trans(0x75); //set行地址
	Data_trans(c);//行地址开始
	Data_trans(d);//行地址结束
	Ins_trans(0x5C);

	for(i=0;i<(d-c+1);i++)
	{
		for(j=0;j<(b-a+1);j++)
		{
			Data_trans(Data);
			Data_trans(Data);
		}
	}
}

