//----------------------------------------------------------
void Delay(Uint times)
  {
   while(times)
   {
    times--;
   }
  }
//----------------------------------------------------------
void M_Delay(Uint NOs)
  {
   while(NOs)
   {
    Delay(50);
    NOs--;
   }
  }

void WriteData(Uchar data1, bit di)
{
       Uchar i,temp;
        CS=0;
		CD=di;
		for(i=0;i<8;i++)
		    {
                  SCK=0;
		  temp=data1;
		  SDA=(bit)(temp&0x80);

		  somenop();
	      SCK=1;
          temp=data1<<1;
	      data1=temp;
 		     }
        CS=1;
		CD=~di;
}

//----------------------------------------------------------
void Init_lcd(void)
  {
   int i;
   RST=0;
   Delay(200);
   RST=1;
   Delay(50000);
   for(i=0;i<8;i++)
   {
    WriteData(IC[i],0);
   }
  }

//----------------------------------------------------------
void Displine(Uchar array[])
  {
   Uint i,j,k;
   for(i=0;i<9;i++)
   {

    WriteData(0x40,0);  //set scroll line
    WriteData(0xb0|i,0);//set page address
    WriteData(0x10,0);  //column  msb
    WriteData(0x00,0);  //column  lsb
    for(j=0;j<48;j++)
    for(k=0;k<4;k++)
    {
     WriteData(array[k],1);
    }
   }
  }

//----------------------------------------------------------

void Dispgraphic(Uchar *p)
    {
	   Uchar i,j;

		   for(i=0;i<8;i++)
		   {
			    WriteData(0x40,0);
			    WriteData(0xb0|i,0);
			    WriteData(0x10,0);
			    WriteData(0x00,0);
			    for(j=0;j<192;j++)
				    {
				     WriteData(p[i*192+j],1);
			         }
           }

  }
  
void lcd_address(Uint page,Uint column)
{
column=column-0x01;
WriteData(0xB0+page-1,0); //设置页地址，每8 行为一页，全屏共64 行，被分成8 页
WriteData(0x10+(column>>4&0x0F),0); //设置列地址的高4 位
WriteData(column&0x0F,0); //设置列地址的低4 位
}


//显示16x16 点阵图像、汉字、生僻字或16x16 点阵的其他图标
void display_graphic_16x16(Uchar page,Uchar column,Uchar *dp)
{
Uint i,j;
for(j=0;j<2;j++)
{
lcd_address(page+j,column);
for (i=0;i<16;i++)
{
WriteData(*dp,1); //写数据到LCD,每写完一个8 位的数据后列地址自动加1
dp++;
}
}
}  

//显示32x64 点阵图像、汉字、生僻字或32x64 点阵的其他图标
void display_graphic_32x64(Uchar page,Uchar column,Uchar *dp)
{
Uint i,j;
for(j=0;j<8;j++)
{
lcd_address(page+j,column);
for (i=0;i<32;i++)
{
WriteData(*dp,1); //写数据到LCD,每写完一个8 位的数据后列地址自动加1
dp++;
}
}
}  
  
