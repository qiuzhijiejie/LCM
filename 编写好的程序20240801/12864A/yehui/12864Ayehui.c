void WriteCommandL( unsigned char CommandByte )   
{   
 BusyL();   
 P1 = CommandByte;   
 RS = 0;   
 RW = 0;   
 E  = 1;   
 _nop_();   
 E  = 0;   
 _nop_();   
}   
/***************************/   
/*Write command 65-128                */   
/***************************/     
void WriteCommandR( unsigned char CommandByte )   
{   
 BusyR();   
 P1 = CommandByte;   
 RS = 0;    
 RW = 0;   
 E  = 1;   
 _nop_();   
 E  = 0;   
 _nop_();   
}   

/***************************/   
/*Read data                 */   
/***************************/   
unsigned char ReadData( void )   
{   
 unsigned char DataByte;   
 Locatexy();   
 RS = 1;    
 RW = 1;  
 P1 = 0xFF;  
  _nop_();   
 
 E  = 1;    
 _nop_();   

 DataByte = P1;  
 E  = 0;   
 _nop_();  
 CS1=0;
 CS2=0;
 return DataByte;   
}   
   
