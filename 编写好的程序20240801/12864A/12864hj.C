//显示128x64 点阵边框
void display_bk()
{
uint i,j;
//左框
for(j=0;j<8;j++)
	{
	wrcomL(0xb8+j);
	wrcomL(0x40+0);
	wrdataL(0xff); 
	wrdataL(0xff); 
	}
	//右框
	for(j=0;j<8;j++)
	{
	wrcomR(0xb8+j);
	wrcomR(0x40+62);
	wrdataR(0xff); 
	wrdataR(0xff); 
	}
	//上框
	wrcomL(0xb8+0);wrcomR(0xb8+0);
	wrcomL(0x40+2);wrcomR(0x40+0);	
	for (i=0;i<62;i++)
	{
	wrdataL(0x03); 
	wrdataR(0x03); 
	}
	//下框
	wrcomL(0xb8+7);wrcomR(0xb8+7);
	wrcomL(0x40+2);wrcomR(0x40+0);	
	for (i=0;i<62;i++)
	{
	wrdataL(0xC0); 
	wrdataR(0xC0); 
	}
}

//显示16x16 点阵图像、汉字、生僻字或16x16 点阵的其他图标
void display_graphic_16x16(uchar hh,uchar page,uchar column,uchar *dp )
{
uint i,j;
	for(j=0;j<2;j++)
	{
		wrcomL(0xb8+page+j);wrcomR(0xb8+page+j);
		if(column<64)
		{
		wrcomL(0x40+column);
			for (i=0;i<16;i++)
			{
			if(hh==0) wrdataL(*dp);
			else wrdataL(~(*dp)); //写数据到LCD,每写完一个8 位的数据后列地址自动加1
			dp++;
			}
		}
		else
		{
		wrcomR(0x40+(column-64));
			for (i=0;i<16;i++)
			{
			if(hh==0) wrdataR(*dp);
			else wrdataR(~(*dp)); //写数据到LCD,每写完一个8 位的数据后列地址自动加1
			dp++;
			}
		}			
	}
}

