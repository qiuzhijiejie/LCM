//----------------------------------------------------------
void Delay(Uint times)
  {
   while(times)
   {
    times--;
   }
  }
//----------------------------------------------------------
void M_Delay(Uint NOs)
  {
   while(NOs)
   {
    Delay(50);
    NOs--;
   }
  }

void WriteData(Uchar data1, bit di)
{
       Uchar i,temp;
        CS=0;
		CD=di;
		for(i=0;i<8;i++)
		    {
                  SCK=0;
		  temp=data1;
		  SDA=(bit)(temp&0x80);

		  somenop();
	      SCK=1;
          temp=data1<<1;
	      data1=temp;
 		     }
        CS=1;
		CD=~di;
}

//----------------------------------------------------------
void Init_lcd(void)
  {
   int i;
   RST=0;
   Delay(200);
   RST=1;
   Delay(50000);
   for(i=0;i<8;i++)
   {
    WriteData(IC[i],0);
   }
  }

//----------------------------------------------------------
void Displine(Uchar array[])
  {
   Uint i,j,k;
   for(i=0;i<9;i++)
   {

    WriteData(0x40,0);  //set scroll line
    WriteData(0xb0|i,0);//set page address
    WriteData(0x10,0);  //column  msb
    WriteData(0x00,0);  //column  lsb
    for(j=0;j<48;j++)
    for(k=0;k<4;k++)
    {
     WriteData(array[k],1);
    }
   }
  }

//----------------------------------------------------------

void Dispgraphic(Uchar *p)
    {
	   Uchar i,j;

		   for(i=0;i<8;i++)
		   {
			    WriteData(0x40,0);
			    WriteData(0xb0|i,0);
			    WriteData(0x10,0);
			    WriteData(0x00,0);
			    for(j=0;j<192;j++)
				    {
				     WriteData(p[i*192+j],1);
			         }
           }

  }
