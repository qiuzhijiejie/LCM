//写指令到LCD模块 
void transfer_command(int data1)    
{ 
char i; 
cs1=0; 
rs=0; 
for(i=0;i<8;i++) 
 {
 sclk=0; 
if(data1&0x80) sid=1; 
else sid=0; 
sclk=1; 
	 data1=data1<<=1; 
 }
 cs1=1; 
} 
//写数据到LCD模块 
void transfer_data(int data1) 
{ 
char i; 
cs1=0; 
rs=1; 
for(i=0;i<8;i++) 
 {
 sclk=0; 
if(data1&0x80) sid=1; 
else sid=0; 
sclk=1; 
data1=data1<<=1; 
 }
 cs1=1; 
} 
//延时 
void delay(int i)                
{ 
 int j,k; 
 for(j=0;j<i;j++) 
for(k=0;k<110;k++); 
} 
void waitkey() 
{ 
repeat:  
if(key==1)goto repeat; 
else delay(400); 
} 
//LCD 模块初始化 
void initial_lcd() 
{ 
reset=0; 
delay(100); 
reset=1;     
       //低电平复位 
 //复位完毕 
delay(100);         
transfer_command(0xe2);  //软复位 
delay(500); 
	transfer_command(0x2f);  //打开内部升压 
delay(500); 
transfer_command(0x81);  //微调对比度 
transfer_command(0x45);  //微调对比度的值，可设置范围0x00～0xFF 
transfer_command(0xeb);  //1/9 偏压比（bias） 
transfer_command(0xc4);  //行扫描顺序：从上到下 oxc2 
transfer_command(0xa0);  //列扫描顺序：从左到右 
transfer_command(0xaf);  //开显示 
} 
void lcd_address(uchar page,uchar column) 
{ 
 column=column-1;  //所以在这里减去1. 
page=page-1; 
transfer_command(0xb0+page);      
   //我们平常所说的第1列，在LCD驱动IC里是第0列。
//设置页地址。每页是8行。一个画面的64行被分成8个页。我们平常所说的第1页，在LCD驱动IC里是第0页，所以在这里减去1 
transfer_command(((column>>4)&0x0f)+0x10); //设置列地址的高 4 位 
transfer_command(column&0x0f);    
//设置列地址的低4位 
} 
//全屏清屏 
void clear_screen() 
{ 
	unsigned char i,j; 
for(i=0;i<9;i++) 
	 {
		lcd_address(1+i,1); 
		for(j=0;j<192;j++) 
	  {
	   transfer_data(0x00);
	  }
	 }
 } 
void display_graphic_192x64(uchar *dp) 
{ 
	uchar i,j; 
	for(i=0;i<9;i++) 
	 {
		 lcd_address(1+i,1); 
		for(j=0;j<192;j++) 
		  {
		   transfer_data
		 (*dp);
		 dp++; 
		  }
	 }
 }  
//==================display a piture of 128*64 dots================ 
void full_display(uchar data_left,uchar data_right) 
{ 
int i,j; 
for(i=0;i<8;i++) 
 {
 lcd_address(i+1,1); 
for(j=0;j<96;j++) 
  {
	  transfer_data(data_left);
	  transfer_data(data_right);
  }
 }           
}         
//显示32x32点阵图像、汉字、生僻字或32x32点阵的其他图标 
