void Delay(unsigned int time)
        {
		  unsigned int i,j;
		  for(i=0;i<time;i++)
		     for(j=0;j<20000;j++)
			       {;}
		}
void Ins_trans(unsigned char command)
  { 
    unsigned char counter;
	  _CS=0;
	  RS=0;
    for(counter=0;counter<8;counter++)
       { 
	     SCL=0;
         SI=(command&0x80)>>7;
         command=command<<1;
	       _nop_();
		     SCL=1;
	     //  _nop_();
		     _nop_();
		     SCL=0;
        }
	RS=1;
   _CS=1;
  }
void Data_trans(unsigned char command)
  { 
    unsigned char counter;
	  _CS=0;
	  RS=1;
    for(counter=0;counter<8;counter++)
       {
         SCL=0;
	     SI=(command&0x80)>>7;
		 command=command<<1;   
	       _nop_();
		     SCL=1;
	      // _nop_();
		     _nop_();
		     SCL=0;
       }
	RS=1;
   _CS=1;
   }
void Column_set(unsigned char column)
          {
		     Ins_trans(0x10|(column>>4));
		     Ins_trans(0x00|(column&0x0f));	 
		  }
void Page_set(unsigned char page)
          {
		    Ins_trans(0xb0+page);
		  }
void Screen_clear()
       {
	     unsigned char page,column;
 		  for(page=0;page<8;page++)             //page loop
		     { 
			   Page_set(page);
			   Column_set(0);	  
			   for(column=0;column<128;column++)	//column loop
			      {
				     Data_trans(0x00);
				    }
			   }
	     }
void Screen_check()
       {
	     unsigned char page,column;
 		  for(page=0;page<8;page++)             //page loop
		     { 
			   Page_set(page);
			   Column_set(0);	  
			   for(column=0;column<128;column++)	//column loop
			      {
				     Data_trans(0xff);
				    }
			   }
	     }
void Initial()
          {
		    unsigned char i;
			for(i=0;i<23;i++)
			   {
			     Ins_trans(initial_tab[i]);
			   }
		  }

void Picture_display(unsigned char *ptr_pic)
        {
		  unsigned char page,column;
		  //Ins_trans(0x81);
		  //Ins_trans(0x1F);
 		  for(page=0;page<(64/8);page++)        //page loop
		     { 
			   Page_set(page);
			   Column_set(0);	  
			   for(column=0;column<128;column++)	//column loop
			      {
				     Data_trans(*ptr_pic++);
				  }
			 }
		  Delay(15);
		}

