void Ins_trans(unsigned char  tData)
{
    unsigned char i;
 
    _CS=0;
    _RS=0;
    for (i=0; i<8; i++)
    {
        SCLK=0;
        if (tData&0x80)
        {//Delay(1);
            SDIN=1;
        }
        else
        {//Delay(1);
            SDIN=0;
        }
        tData = tData << 1;
        SCLK=1;
    }
    _RS=1;
    _CS=1;
}
 
void Data_trans(unsigned char  tData)
{
    unsigned char i;
 
    _CS=0;
    _RS=1;
    for (i=0; i<8; i++)
    {
        SCLK=0;
        if (tData&0x80)
        {//Delay(1);
            SDIN=1;
        }
        else
        {//Delay(1);
            SDIN=0;
        }
        tData = tData << 1;
        SCLK=1;
    }
    _RS=1;
    _CS=1;
}
 
