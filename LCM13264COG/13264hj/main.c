/*LCD 模块初始化*/
void initial_lcd()
{
cs1=0;
reset=0; /*低电平复位*/
delay(20);
reset=1; /*复位完毕*/
delay(20);
transfer_command(0xe2); /*软复位*/
delay(50);
transfer_command(0x2c); /*升压步聚1*/
delay(50);
transfer_command(0x2e); /*升压步聚2*/
delay(50);
transfer_command(0x2f); /*升压步聚3*/
delay(50);
transfer_command(0x24); /*粗调对比度，可设置范围0x20～0x27*/
transfer_command(0x81); /*微调对比度*/
transfer_command(0x28); /*0x1a,微调对比度的值，可设置范围0x00～0x3f 1f*/
transfer_command(0xa2); /*1/9 偏压比（bias）*/
transfer_command(0xc8); /*行扫描顺序：从上到下*/
transfer_command(0xa0); /*列扫描顺序：从左到右*/
transfer_command(0x60); /*起始行：第一行开始*/
transfer_command(0xaf); /*开显示*/
cs1=1;
}


void lcd_address(uchar page,uchar column)
{

cs1=0;
column=column; //
page=page-1;
transfer_command(0xb0+page); 
transfer_command(((column>>4)&0x0f)+0x10); //设置列地址的高4 位
transfer_command(column&0x0f); //设置列地址的低4 位
}


/*全屏清屏*/
void clear_screen()
{
unsigned char i,j;
cs1=0;
for(i=0;i<8;i++)
{
lcd_address(1+i,1);
for(j=0;j<132;j++)
{
transfer_data(0x00);
}
}
cs1=1;
}


void test_display(uchar data1,uchar data2)
{
int i,j;
for(j=0;j<9;j++)
{
cs1=0;
lcd_address(j+1,1);//页，列地址
for(i=0;i<64;i++)
{
transfer_data(data1);
transfer_data(data2);
}
}
}


void display_string_8x16(uchar fb,uint page,uint column,uchar *text)
{
uint i=0,j,k,n;
cs1=0;
while(text[i]>0x00)
{
if((text[i]>=0x20)&&(text[i]<=0x7e))
{
j=text[i]-0x20;

for(n=0;n<2;n++)
{
lcd_address(page+n,column);
for(k=0;k<8;k++)
{
if (fb==1) transfer_data(ascii_table_8x16[j][k+8*n]);
else transfer_data(~(ascii_table_8x16[j][k+8*n]));
}
}
i++;
column+=8;
}
else
i++;
}
}


void display_string_8x16_t(uchar fb,uint page,uint column,uchar text)
{
	uint j,k,n;
	j=text+16;
	for(n=0;n<2;n++)
	{				
	lcd_address(page+n,column);
		for(k=0;k<8;k++)
		{
		if (fb==1) transfer_data(ascii_table_8x16[j][k+8*n]);
		else transfer_data(~(ascii_table_8x16[j][k+8*n]));
		}
	}
		
} 
 
 
void display_string_5x8(uint page,uint column,uchar *text)

{
uint i=0,j,k;
cs1=0;
while(text[i]>0x00)
{
if((text[i]>=0x20)&&(text[i]<0x7e))	
{
j=text[i]-0x20;
lcd_address(page,column);
for(k=0;k<5;k++)					
{
transfer_data(ascii_table_5x8[j][k]);
}
i++;
column+=6;							
}
else
i++;
}
}




void display_graphic_16x16(uchar fb,uchar page,uchar column,uchar *dp)
{
uint i,j;
for(j=0;j<2;j++)
{
lcd_address(page+j,column);
for (i=0;i<16;i++)
{
if(fb==1) transfer_data(*dp);
else transfer_data(~(*dp)); 
dp++;
}
}
}


