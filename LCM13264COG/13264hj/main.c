//=============transfer command to LCM===============串口

void transfer_command(int data1)

{
char i;
cs1=0;
rs=0;
for(i=0;i<8;i++)
{
lcd_sclk=0;
//delay_us(10); //加少量延时
if(data1&0x80) lcd_sid=1;
else lcd_sid=0;
lcd_sclk=1;
//delay_us(10); //加少量延时
data1=data1<<=1;
}
cs1=1;
}




//-----------transfer data to LCM---------------
void transfer_data(int data1)
{
char i;

cs1=0;
rs=1;
for(i=0;i<8;i++)
{
lcd_sclk=0;
if(data1&0x80) lcd_sid=1;
else lcd_sid=0;
lcd_sclk=1;
data1=data1<<=1;
}
cs1=1;
}



