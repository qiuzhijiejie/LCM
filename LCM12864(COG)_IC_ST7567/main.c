void lcd_address(uchar page,uchar column) 
{ 
	column=column-1; //我们平所说的第1列，在LCD驱动IC里是第0列。所以在这里减1
	page=page-1; //设置页地址。每页是8行。一个画面的64行被分成8个页。我们平常
//				说的第1页，在LCD驱动IC里是第0页，所以在这里减去1*/ 
	
	transfer_command_lcd(0xb0+page); 
	transfer_command_lcd(((column>>4)&0x0f)+0x10); //设置列地址的高4位 
	transfer_command_lcd(column&0x0f);             //设置列地址的低4位 
} 


