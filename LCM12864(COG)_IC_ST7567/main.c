void sleep() 
{ 
	transfer_command_lcd(0xac);/*静态图标关闭*/ 
	transfer_command_lcd(0x00);/*静态图标寄存器设置：关闭。此指令与上述指令一起完成静态图标关闭*/ 
	transfer_command_lcd(0xae);/*显示：关*/ 
	transfer_command_lcd(0xa5);/*全屏显示：开*/ 
} 

