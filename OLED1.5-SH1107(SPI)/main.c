  {
    OLED_send_cmd(0xb0+page);
  }
void OLED_clear(void)
  {
    unsigned char page,column;
    for(page=0;page<OLED_PAGE_NUMBER;page++)             //page loop
      { 
          Page_set(page);
          Column_set(0);	  
          for(column=0;column<OLED_COLUMN_NUMBER;column++)	//column loop
            {
              OLED_send_data(0x00);
            }
      }
  }
  
void OLED_full(unsigned char oddData, unsigned char evenData)
{
    unsigned char page, column;
    for(page = 0; page < OLED_PAGE_NUMBER; page++)   // page loop
    { 
        Page_set(page);
        Column_set(0);	  
        for(column = 0; column < OLED_COLUMN_NUMBER; column++) // column loop
        {
            if(column % 2 == 0)      // 偶数列
                OLED_send_data(evenData);
            else                     // 奇数列
                OLED_send_data(oddData);
        }
    }
}
  
