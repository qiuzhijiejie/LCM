void BusyL(void)   
{unsigned char flag=0xff;  
 CS1= 1;       //active "H"
 CS2= 0;   
 RS = 0;   
 RW = 1;  

 P1 = 0xFF; 
while ((flag&0x80)==0x80)
 {
 E=1;
 _nop_();
 flag=P1;
 E=0;
 }    
}   
   
void BusyR(void)   
{ unsigned char flag=0xff;  
 CS1= 0;   
 CS2= 1;        //active "H"
 RS = 0;    
 RW = 1; 

 P1 = 0xFF;  
while ((flag&0x80)==0x80)
 {
 E=1;
 _nop_();
 flag=P1;
 E=0;
 }  
}   
   
 

   
  
void Locatexy(void)   
{   
 unsigned char x,y;   
 switch (Col&0xc0) /*  col.and.0xC0 */   
 {    
  case 0: {BusyL();break;}  
  case 0x40: {BusyR();break;}  
 }   
 x = Col&0x3F|0x40; /* col.and.0x3f.or.Set X Address*/   
 y = Page&0x07|0xB8; /* row.and.0x07.or.set Page */   
   
 RS = 0;      
 RW = 0;      
 P1 = y;  
 E  = 1;   
 _nop_();   
 E  = 0;   
 _nop_();   
 
 RS = 0;   
 RW = 0;   
 P1 = x;      
 E  = 1;   
 _nop_();   
 E  = 0;   
 _nop_(); 
 

}   
