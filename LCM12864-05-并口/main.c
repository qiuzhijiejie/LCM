{   
 Locatexy();   
 RS = 1;    
 RW = 0;     
 P1 = DataByte; 
 E  = 1;    
 _nop_();   
 E  = 0;   
 _nop_(); 
 CS1=0;
 CS2=0;
}   
   
void LcmClear( void )   
{   
 Page = 0;   
 Col  = 0;   
 for(Page=0;Page<8;Page++)   
  for(Col=0;Col<128;Col++)   
   WriteData(0);   
}   
   
void LcmInit( void )   
{   
 WriteCommandL(0x3f); //DISPALY ON
 WriteCommandR(0x3f);   
   
 WriteCommandL(0xc0); //SET START ADDRESS  
 WriteCommandR(0xc0);   
   
 WriteCommandL(0x3f); //DISPLAY ON  
 WriteCommandR(0x3f);   
     
}   
   
void LcmPutDots( unsigned char DotByte,unsigned char DotByte1 )   
{   
 Page = 0;   
 Col  = 0;   
 for(Page=0;Page<8;Page++)   
 {   
  for(Col=0;Col<128;Col++)   
  {   
   WriteData( DotByte );
   Col++;
   WriteData( DotByte1 );  
  } 
    
 }   
}   
   
void LcmPutBMP( unsigned char *puts )   
{   
 unsigned int X=0;   
 Page = 0;   
 Col  = 0;   
 for(Page=0;Page<8;Page++)   
 {   
  for(Col=0;Col<128;Col++)   
  {   
   WriteData( puts[X] );   
   X++;   
  }   
 }   
}   
   
void LcmReverseBMP( void )   
{   
 unsigned char temp;   
 Page = 0;   
 Col  = 0;   
 for(Page=0;Page<8;Page++)   
 {   
  for(Col=0;Col<128;Col++)   
  {   
   temp = ReadData();   

   temp = ReadData();   
   temp = ~temp;   
   WriteData(temp);   
  }   
 }   
}   

